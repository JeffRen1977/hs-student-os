#!/usr/bin/env bash
# Deploy web/ to Firebase Hosting for staging (https://${PROJECT_ID}.web.app).
#
#   PROJECT_ID=hs-student-os REGION=us-central1 ./deploy/staging/deploy_web.sh
#
# Builds a copy of web/ in a temp dir with config.js pointing at the staging API and the
# project's Firebase web app, then deploys it. The repo's web/config.js stays empty.
# The API's HSOS_CORS_ALLOWED_ORIGINS (api.env.yaml) must list the hosting origins.
set -euo pipefail

: "${PROJECT_ID:?set PROJECT_ID}"
REGION="${REGION:-us-central1}"
case "$PROJECT_ID" in demo-*) echo "refusing: demo-* projects are emulator-only" >&2; exit 2 ;; esac
REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"

API_URL="$(gcloud run services describe hsos-api --project "$PROJECT_ID" --region "$REGION" --format 'value(status.url)')"
[ -n "$API_URL" ] || { echo "hsos-api is not deployed (run provision.sh first)" >&2; exit 3; }
APP_ID="$(firebase apps:list WEB --project "$PROJECT_ID" --json | python3 -c '
import json, sys
apps = [a for a in json.load(sys.stdin)["result"] if a.get("displayName") == "hsos-web"]
print(apps[0]["appId"] if apps else "")')"
[ -n "$APP_ID" ] || { echo "no Firebase web app named hsos-web (firebase apps:create WEB hsos-web)" >&2; exit 3; }

BUILD="$(mktemp -d)"
trap 'rm -rf "$BUILD"' EXIT
mkdir -p "$BUILD/public"
cp -R "$REPO_ROOT/web/." "$BUILD/public/"
rm -rf "$BUILD/public/tests"
SDK_JSON="$(firebase apps:sdkconfig WEB "$APP_ID" --project "$PROJECT_ID" --json | python3 -c '
import json, sys
print(json.dumps(json.load(sys.stdin)["result"]["sdkConfig"]))')"
cat >"$BUILD/public/config.js" <<JS
// Generated by deploy/staging/deploy_web.sh for ${PROJECT_ID}.
window.HS_API_BASE_URL = "${API_URL}";
window.HS_FIREBASE_CONFIG = ${SDK_JSON};
JS
cat >"$BUILD/firebase.json" <<'JSON'
{"hosting": {"public": "public", "headers": [{"source": "**", "headers": [{"key": "Cache-Control", "value": "no-cache"}]}]}}
JSON
(cd "$BUILD" && firebase deploy --only hosting --project "$PROJECT_ID" --non-interactive)
echo "web: https://${PROJECT_ID}.web.app  →  API ${API_URL}"
